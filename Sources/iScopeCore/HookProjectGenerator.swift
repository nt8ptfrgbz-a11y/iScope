import Foundation

public struct HookSignature: Sendable {
    public let returnType: String
    public let argumentTypes: [String]
}

public struct HookProjectConfiguration: Sendable {
    public var name: String
    public var bundleIdentifier: String
    public var methods: [ObjCMethod]
    public init(name: String, bundleIdentifier: String, methods: [ObjCMethod]) {
        self.name = name; self.bundleIdentifier = bundleIdentifier; self.methods = methods
    }
}

public struct GeneratedProjectFile: Sendable {
    public let path: String
    public let content: String
}

/// Generates an iOS dynamic library project without invoking a shell or downloading dependencies.
public enum HookProjectGenerator {
    public static func targetClassName(_ method: ObjCMethod) -> String {
        String(method.className.prefix { $0 != "(" })
    }

    public static func signature(for method: ObjCMethod) throws -> HookSignature {
        guard !method.selector.isEmpty, !method.selector.contains("\0"), !targetClassName(method).isEmpty else {
            throw ScopeError.invalid("方法名或类名无效。")
        }
        var decoder = HookTypeReader(method.typeEncoding)
        let types = try decoder.readAll()
        let argumentCount = method.selector.filter { $0 == ":" }.count
        guard types.count == argumentCount + 3, types[1] == "id", types[2] == "SEL", !types.dropFirst(3).contains("void") else {
            throw ScopeError.invalid("类型编码与 Selector 参数数量不匹配。")
        }
        return HookSignature(returnType: types[0], argumentTypes: Array(types.dropFirst(3)))
    }

    public static func files(for configuration: HookProjectConfiguration) throws -> [GeneratedProjectFile] {
        try validate(configuration)
        let methods = uniqueMethods(configuration.methods)
        let name = configuration.name
        return [
            GeneratedProjectFile(path: "\(name).xcodeproj/project.pbxproj", content: project(name)),
            GeneratedProjectFile(path: "\(name).xcodeproj/xcshareddata/xcschemes/\(name).xcscheme", content: scheme(name)),
            GeneratedProjectFile(path: "Hooks.m", content: try source(configuration)),
            GeneratedProjectFile(path: "HookTargets.json", content: try manifest(configuration, methods: methods)),
            GeneratedProjectFile(path: "README.md", content: readme(configuration, count: methods.count)),
            GeneratedProjectFile(path: ".gitignore", content: "build/\nDerivedData/\nxcuserdata/\n.DS_Store\n*.ipa\niScopeOutput/\niScopeWorkflow.local.json\n")
        ]
    }

    /// Writes through a staging directory, then moves into place without replacing an existing project.
    public static func write(_ configuration: HookProjectConfiguration, to parent: URL) throws -> URL {
        let files = try files(for: configuration)
        let fm = FileManager.default
        let destination = parent.appendingPathComponent(configuration.name, isDirectory: true)
        guard !fm.fileExists(atPath: destination.path) else { throw ScopeError.invalid("目标目录已存在，请修改工程名或选择其他位置。") }
        let staging = parent.appendingPathComponent(".iScope-hook-\(UUID().uuidString)", isDirectory: true)
        try fm.createDirectory(at: staging, withIntermediateDirectories: false)
        do {
            for file in files {
                try Task.checkCancellation()
                let url = staging.appendingPathComponent(file.path)
                try fm.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
                try file.content.write(to: url, atomically: true, encoding: .utf8)
            }
            try fm.moveItem(at: staging, to: destination)
            return destination
        } catch { try? fm.removeItem(at: staging); throw error }
    }

    public static func source(_ configuration: HookProjectConfiguration) throws -> String {
        try validate(configuration)
        let methods = uniqueMethods(configuration.methods)
        var lines = ["""
        // Generated by iScope. Edit the IScopeReplacement_* function bodies below.
        // This target uses manual reference counting to preserve method-family ownership semantics.
        #import <Foundation/Foundation.h>
        #import <UIKit/UIKit.h>
        #import <QuartzCore/QuartzCore.h>
        #import <objc/runtime.h>
        #import <mach-o/dyld.h>
        #import <stdatomic.h>
        #import <stdbool.h>
        #import <string.h>

        static BOOL IScopeSignatureMatches(const char *actual, const char *expected) {
            if (!actual || !expected) return NO;
            NSMethodSignature *a = [NSMethodSignature signatureWithObjCTypes:actual];
            NSMethodSignature *b = [NSMethodSignature signatureWithObjCTypes:expected];
            if (!a || !b || a.numberOfArguments != b.numberOfArguments || strcmp(a.methodReturnType, b.methodReturnType)) return NO;
            for (NSUInteger i = 0; i < a.numberOfArguments; i++) {
                if (strcmp([a getArgumentTypeAtIndex:i], [b getArgumentTypeAtIndex:i])) return NO;
            }
            return YES;
        }
        """]
        for (index, method) in methods.enumerated() {
            let signature = try signature(for: method)
            let arguments = signature.argumentTypes.enumerated().map { ", \($0.element) arg\($0.offset + 1)" }.joined()
            let types = signature.argumentTypes.map { ", " + $0 }.joined()
            let callArguments = signature.argumentTypes.indices.map { ", arg\($0 + 1)" }.joined()
            lines.append("""

            // \(oneLine(method.signature))  |  original VM address: \(method.address.hex)
            typedef \(signature.returnType) (*IScopeOriginalType_\(index))(id, SEL\(types));
            static IScopeOriginalType_\(index) IScopeOriginal_\(index) = NULL;
            static BOOL IScopeInstalled_\(index) = NO;
            static BOOL IScopeWarned_\(index) = NO;

            static \(signature.returnType) IScopeReplacement_\(index)(id self, SEL _cmd\(arguments)) {
                // TODO: 在这里修改 \(oneLine(method.selector)) 的实现。
                // 调用 IScopeOriginal_\(index)(self, _cmd\(callArguments)) 可继续执行原方法。
                \(signature.returnType == "void" ? "" : "return ")IScopeOriginal_\(index)(self, _cmd\(callArguments));
            }
            """)
        }
        lines.append("\nstatic void IScopeInstallHooks(void) {\n    @autoreleasepool {")
        for (index, method) in methods.enumerated() {
            lines.append("""
                    if (!IScopeInstalled_\(index)) {
                        Class targetClass = objc_getClass(\(literal(targetClassName(method))));
                        Class host = \(method.isClassMethod ? "object_getClass(targetClass)" : "targetClass");
                        SEL selector = sel_registerName(\(literal(method.selector)));
                        Method method = host ? class_getInstanceMethod(host, selector) : NULL;
                        if (method) {
                            const char *types = method_getTypeEncoding(method);
                            if (IScopeSignatureMatches(types, \(literal(method.typeEncoding)))) {
                                IScopeOriginal_\(index) = (IScopeOriginalType_\(index))method_getImplementation(method);
                                if (IScopeOriginal_\(index)) {
                                    // Add on the target class first, so an inherited method does not modify its superclass.
                                    if (!class_addMethod(host, selector, (IMP)IScopeReplacement_\(index), types)) {
                                        IMP previous = class_replaceMethod(host, selector, (IMP)IScopeReplacement_\(index), types);
                                        if (previous) IScopeOriginal_\(index) = (IScopeOriginalType_\(index))previous;
                                    }
                                    IScopeInstalled_\(index) = YES;
                                    NSLog(@"[iScope] Installed %@", @\(literal(method.signature)));
                                }
                            } else if (!IScopeWarned_\(index)) {
                                IScopeWarned_\(index) = YES;
                                NSLog(@"[iScope] Skipped signature mismatch: %@", @\(literal(method.signature)));
                            }
                        }
                    }
            """)
        }
        lines.append("""
            }
        }

        // The dyld callback only schedules work. ObjC runtime calls happen later on the main queue.
        static atomic_bool IScopeInstallScheduled = false;
        static void IScopeScheduleInstall(void) {
            if (atomic_exchange(&IScopeInstallScheduled, true)) return;
            dispatch_async(dispatch_get_main_queue(), ^{
                IScopeInstallHooks();
                atomic_store(&IScopeInstallScheduled, false);
            });
        }
        static void IScopeImageAdded(const struct mach_header *header, intptr_t slide) {
            IScopeScheduleInstall();
        }

        __attribute__((constructor)) static void IScopeEntry(void) {
            @autoreleasepool {
                if (![[NSBundle mainBundle].bundleIdentifier isEqualToString:@\(literal(configuration.bundleIdentifier))]) return;
                _dyld_register_func_for_add_image(IScopeImageAdded);
                IScopeScheduleInstall();
            }
        }
        """)
        return lines.joined(separator: "\n") + "\n"
    }

    private static func validate(_ configuration: HookProjectConfiguration) throws {
        guard configuration.name.range(of: "^[A-Za-z][A-Za-z0-9_]{0,47}$", options: .regularExpression) != nil else {
            throw ScopeError.invalid("工程名需以英文字母开头，只能包含字母、数字和下划线，最多 48 字符。")
        }
        guard configuration.bundleIdentifier.range(of: "^[A-Za-z0-9-]+(?:\\.[A-Za-z0-9-]+)+$", options: .regularExpression) != nil else {
            throw ScopeError.invalid("请输入有效的目标 Bundle ID，例如 com.example.app。")
        }
        guard !configuration.methods.isEmpty else { throw ScopeError.invalid("请至少选择一个 Objective-C 方法。") }
        for method in configuration.methods { _ = try signature(for: method) }
    }

    private static func uniqueMethods(_ methods: [ObjCMethod]) -> [ObjCMethod] {
        var seen = Set<String>()
        return methods.filter { seen.insert("\(targetClassName($0))|\($0.isClassMethod)|\($0.selector)").inserted }
    }

    private static func literal(_ value: String) -> String {
        // JSON string escapes are also valid for the UTF-8 C / ObjC literals emitted here.
        let data = try! JSONEncoder().encode(value)
        return String(decoding: data, as: UTF8.self).replacingOccurrences(of: "\\/", with: "/")
    }
    private static func oneLine(_ text: String) -> String {
        text.replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "\r", with: " ").replacingOccurrences(of: "\\", with: " ")
    }

    private static func manifest(_ configuration: HookProjectConfiguration, methods: [ObjCMethod]) throws -> String {
        struct Manifest: Encodable {
            let generator = "iScope"
            let targetBundleIdentifier: String
            let methods: [ObjCMethod]
        }
        let encoder = JSONEncoder(); encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        return String(decoding: try encoder.encode(Manifest(targetBundleIdentifier: configuration.bundleIdentifier, methods: methods)), as: UTF8.self) + "\n"
    }

