    private static func readme(_ configuration: HookProjectConfiguration, count: Int) -> String {
        """
        # \(configuration.name)

        iScope 生成的 iOS Hook 动态库工程，目标 Bundle ID：`\(configuration.bundleIdentifier)`，包含 \(count) 个 Objective-C 方法。

        ## 编辑与编译

        可直接在 iScope 的“编译与部署”面板选择本工程，在内置编辑器修改 `Hooks.m`，然后执行编译、注入、重签和安装。运行前自动保存，签名材料支持自动匹配；只编译 / 注入也可单独执行。

        如需使用 Xcode 手动编译：

        1. 用 Xcode 打开 `\(configuration.name).xcodeproj`。
        2. 打开 `Hooks.m`，修改各个 `IScopeReplacement_*` 函数体。每段上方都写有原始类名、Selector 和方法地址。
        3. 默认实现透传原方法；`IScopeOriginal_*(self, _cmd, arg1, ...)` 用于继续调用原实现。不要在替换函数里用 `[self 同名方法]` 调原实现，否则可能递归。
        4. 选择 **Any iOS Device (arm64)**，使用 **Product → Build（⌘B）**。该工程生成 dylib，不是可直接 Run 的 App。
        5. 在 Products 中右键 `\(configuration.name).dylib` → Show in Finder，取得产物。

        目标默认 iOS 15+ / arm64，不依赖 Theos、Logos 或第三方 Hook 库。动态库使用 Objective-C runtime 替换 IMP；对于 arm64e 专用测试包，请在 Build Settings 中将 ARCHS 改为对应架构并重新编译。

        ## 放入自己的测试 IPA

        iScope 的部署面板会自动将 dylib 放入目标 `.app/Frameworks/`，添加 `@executable_path/Frameworks/\(configuration.name).dylib` 加载项，再完成嵌套代码及整个 App 的重签名、打包和安装。每次使用独立输出目录，不覆盖原 IPA。

        重签默认使用原 Bundle ID 加 `.regisn`，可自定义；Hook 的 Bundle ID 过滤条件会在构建副本中同步更新，原源码保留。默认移除副本的 App 扩展、Watch 和 App Clips，保留 URL Schemes。签名需要有效的本机证书与私钥，以及匹配目标 ID / 设备的描述文件。安装失败后可只重试已有签名 IPA。

        ## 安装行为

        - 仅在 Bundle ID 匹配时安装 Hook。
        - 通过 dyld 新镜像通知在主队列延迟安装，以覆盖已加载及后加载 Framework 中的 Objective-C 类。
        - 校验运行时方法签名，匹配才替换；不匹配会在控制台输出 `[iScope] Skipped signature mismatch`。
        - 继承的方法优先添加到目标类，避免直接修改父类的实现。类方法安装在 metaclass 上。
        - 工程关闭 ARC，以便默认透传代码保留 alloc / init / copy 等方法族的所有权语义；自定义实现中请遵守对应的返回值与内存管理约定。
        - 纯 Swift 非 `@objc` 方法、C/C++ 函数、未知结构体、联合体、向量和可变参数方法不由此模板覆盖。元数据不能可靠识别可变参数，选择此类方法前需自行确认真实签名。
        - Hook 仅作用于实际经过该 IMP 的 Objective-C 派发；直接调用或后续其他库再次替换 IMP 可能绕过此实现。实际安装与行为需要在目标测试 App 中验证。

        `HookTargets.json` 保留原始类型编码和分析地址；安装按类名与 Selector 查找，不依赖固定地址或 ASLR 偏移。
        """
    }
}

private struct HookTypeReader {
    let chars: [Character]
    var index = 0
    init(_ text: String) { chars = Array(text) }
    private static let scalar: [Character: String] = ["v": "void", "c": "char", "C": "unsigned char", "s": "short", "S": "unsigned short", "i": "int", "I": "unsigned int", "l": "long", "L": "unsigned long", "q": "long long", "Q": "unsigned long long", "f": "float", "d": "double", "D": "long double", "B": "BOOL", "#": "Class", ":": "SEL", "*": "char *"]

    mutating func readAll() throws -> [String] {
        var result: [String] = []
        while index < chars.count {
            if chars[index].isNumber || chars[index] == "+" || chars[index] == "-" { index += 1; continue }
            result.append(try readType(depth: 0))
        }
        return result
    }

    mutating func readType(depth: Int) throws -> String {
        guard index < chars.count, depth < 32 else { throw ScopeError.invalid("方法类型编码不完整或嵌套过深。") }
        let c = chars[index]; index += 1
        if let type = Self.scalar[c] { return type }
        switch c {
        case "r", "n", "N", "o", "O", "R", "V": return try readType(depth: depth + 1)
        case "@":
            if index < chars.count && chars[index] == "?" { index += 1 }
            else if index < chars.count && chars[index] == "\"" {
                index += 1
                while index < chars.count && chars[index] != "\"" { index += 1 }
                guard index < chars.count else { throw ScopeError.invalid("对象类型名称不完整。") }
                index += 1
            }
            return "id"
        case "^":
            if index < chars.count && chars[index] == "?" { index += 1; return "void *" }
            if index < chars.count && [Character("{"), "(", "["].contains(chars[index]) {
                let opening = chars[index], closing: Character = opening == "{" ? "}" : opening == "(" ? ")" : "]"
                var nested = 0
                repeat {
                    if chars[index] == opening { nested += 1 }; if chars[index] == closing { nested -= 1 }; index += 1
                } while index < chars.count && nested > 0
                guard nested == 0 else { throw ScopeError.invalid("指针目标类型不完整。") }
                // All data pointers have the same ABI; the private pointee declaration is not needed for forwarding.
                return "void *"
            }
            return try readType(depth: depth + 1) + " *"
        case "{":
            let encodingStart = index - 1
            let start = index
            while index < chars.count && chars[index] != "=" && chars[index] != "}" { index += 1 }
            let name = String(chars[start..<index])
            var nested = 1
            while index < chars.count && nested > 0 {
                if chars[index] == "{" { nested += 1 }; if chars[index] == "}" { nested -= 1 }; index += 1
            }
            guard nested == 0 else { throw ScopeError.invalid("结构体类型编码不完整。") }
            let rawEncoding = String(chars[encodingStart..<index])
            var unquoted = "", inQuote = false
            for character in rawEncoding {
                if character == "\"" { inQuote.toggle() }
                else if !inQuote { unquoted.append(character) }
            }
            let known = ["CGPoint": "CGPoint", "CGSize": "CGSize", "CGRect": "CGRect", "CGVector": "CGVector", "CGAffineTransform": "CGAffineTransform", "CATransform3D": "CATransform3D", "UIEdgeInsets": "UIEdgeInsets", "NSDirectionalEdgeInsets": "NSDirectionalEdgeInsets", "UIOffset": "UIOffset", "_NSRange": "NSRange", "NSRange": "NSRange"]
            let layouts = ["CGPoint": "{CGPoint=dd}", "CGSize": "{CGSize=dd}", "CGRect": "{CGRect={CGPoint=dd}{CGSize=dd}}", "CGVector": "{CGVector=dd}",
                           "CGAffineTransform": "{CGAffineTransform=dddddd}", "CATransform3D": "{CATransform3D=dddddddddddddddd}", "UIEdgeInsets": "{UIEdgeInsets=dddd}",
                           "NSDirectionalEdgeInsets": "{NSDirectionalEdgeInsets=dddd}", "UIOffset": "{UIOffset=dd}", "_NSRange": "{_NSRange=QQ}", "NSRange": "{NSRange=QQ}"]
            guard let type = known[name], layouts[name] == unquoted else { throw ScopeError.invalid("结构体 \(name) 的布局无法确认，需手动处理 Hook 签名。") }
            return type
        default: throw ScopeError.invalid("暂不支持类型编码“\(c)”；此方法需要手动处理 ABI。")
        }
    }
}
